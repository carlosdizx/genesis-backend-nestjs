import { Sequelize } from 'sequelize-typescript';
import TestEntityModel from './fixtures/test-entity.model';
import RepositoryOptionsInterface from '../../src/database/interfaces/repository-options.interface';
import { ConflictException, Logger, NotFoundException } from '@nestjs/common';
import AbstractRepository from '../../src/database/repositories/abstract.repository';
import TestRepository from './fixtures/test.repository';
import { randomUUID } from 'node:crypto';

const length = 10000;
const logger = new Logger('Test logger');
const opts: RepositoryOptionsInterface<TestEntityModel> = {
  logger,
  createMessage: 'No se pudo crear el registro',
  insertManyMessage: 'No se pudieron crear los registros',
  findOrCreateMessage: 'No se pudo buscar o crear el registro',
  findByPkMessage: 'No se pudo buscar el registro',
  findByPkNotFoundMessage: 'Registro no encontrado',
  findOneMessage: 'No se pudo buscar el registro',
  findOneNotFoundMessage: 'Registro no encontrado',
  findAllMessage: 'No se pudieron listar los registros',
  findAllPaginatedMessage: 'No se pudieron listar los registros',
  updateByPkMessage: 'No se pudo actualizar el registro',
  updateByQueryMessage: 'No se pudo actualizar el registro',
  deleteByPkMessage: 'No se pudo eliminar el registro',
  restoreByPkMessage: 'No se pudo restaurar el registro',
  transactionMessage: 'No se pudo completar la transacción',
};

let repository: TestRepository;

describe('AbstractRepository', () => {
  let sequelize: Sequelize;

  beforeEach(async () => {
    sequelize = new Sequelize({
      dialect: 'sqlite',
      storage: ':memory:',
      logging: false,
      models: [TestEntityModel],
    });

    repository = new TestRepository(TestEntityModel, opts);
    repository.unassignLoggerError();

    await sequelize.sync({ force: true });
  });

  afterEach(async () => {
    await sequelize.close();
  });

  describe('Constructor - Incorrect Instance', () => {
    it('should be throw exception to directly instance', () => {
      expect(() => new AbstractRepository(TestEntityModel, {})).toThrow(
        ConflictException,
      );
    });
  });

  describe('Constructor - Instance', () => {
    it('should be not throw exception to instance', () => {
      repository = new TestRepository(TestEntityModel, opts);
      expect(repository).toBeDefined();
    });
  });

  describe('Id Object', () => {
    it('should be generated by custom function', () => {
      repository = new TestRepository(TestEntityModel, {
        ...opts,
        idGenerator: randomUUID,
      });

      repository.create({});
    });

    it('should be generated by custom function', () => {
      repository = new TestRepository(TestEntityModel, opts);

      repository.create({});
    });
  });

  describe('Create Method', () => {
    it('should be correct', async () => {
      const entity = await repository.create({});

      expect(entity).toBeDefined();
      expect(entity.id).toBeDefined();
      expect(entity).toHaveProperty('id');
    });

    describe('Ids uniques', () => {
      it('should be generated by custom function', async () => {
        const fn = () => 'notUniqueId';

        repository = new TestRepository(TestEntityModel, {
          ...opts,
          idGenerator: fn,
        });

        const original = await repository.create({ id: fn() });
        expect(original).toBeDefined();
        expect(original).toHaveProperty('id');

        const duplicated = repository.create({ id: fn() });

        await expect(duplicated).rejects.toThrow();
        await expect(duplicated).rejects.toThrow(ConflictException);
        await expect(duplicated).rejects.toThrow(opts.createMessage);
      });
    });
  });

  describe('Insert Many Method', () => {
    it('should be correct', async () => {
      repository = new TestRepository(TestEntityModel, {
        ...opts,
        idGenerator: randomUUID,
      });

      const entities = [];
      for (let i = 0; i < length; i++) {
        entities.push({ name: `name-${i}` });
      }

      const entity = await repository.insertMany(entities);

      expect(entity).toBeDefined();
      expect(entity).toHaveLength(length);
      expect(entity).toHaveProperty('length');

      const entitiesFound = await repository.findAll();
      expect(entitiesFound).toHaveLength(length);
    });

    it('Ids duplicates', async () => {
      repository = new TestRepository(TestEntityModel, {
        ...opts,
        idGenerator: () => 'notUniqueId',
      });

      const entities = [];
      for (let i = 0; i < length; i++) {
        entities.push({ name: `name-${i}` });
      }

      const res = repository.insertMany(entities);

      await expect(res).rejects.toThrow();
      await expect(res).rejects.toThrow(ConflictException);
      await expect(res).rejects.toThrow(opts.insertManyMessage);
    });
  });

  describe('Find or Create Method', () => {
    it('should be correct', async () => {
      const id = 'id';

      const [, first] = await repository.findOrCreate({
        where: { id },
        defaults: { id, name: randomUUID() },
      });

      const [, second] = await repository.findOrCreate({
        where: { id },
        defaults: { id, name: randomUUID() },
      });

      const [, third] = await repository.findOrCreate({
        where: { id: id.concat(id) },
      });

      expect(first).toBeTruthy();
      expect(second).toBeFalsy();
      expect(third).toBeTruthy();
    });

    it('Wrong Data', async () => {
      const res = repository.findOrCreate({});

      await expect(res).rejects.toThrow();
      await expect(res).rejects.toThrow(ConflictException);
      await expect(res).rejects.toThrow(opts.findOrCreateMessage);
    });
  });

  describe('find by PK Method', () => {
    it('should be correct', async () => {
      const id = randomUUID();
      const name = randomUUID().concat('-name');

      await repository.create({ id, name });

      const found = await repository.findByPk(id, false);

      expect(found).toBeDefined();
      expect(found).toHaveProperty('id');
      expect(found).toHaveProperty('name');
      expect(found.name).toEqual(name);
      expect(found.id).not.toEqual(name);
    });

    it('should be not found', async () => {
      const id = randomUUID();

      await repository.create({ id });

      const found = repository.findByPk('id', true);

      await expect(found).rejects.toThrow();
      await expect(found).rejects.toThrow(NotFoundException);
      await expect(found).rejects.toThrow(opts.findByPkNotFoundMessage);
    });

    it('should be throw exception', async () => {
      const id = [undefined] as unknown as string;

      await repository.create({ id });

      const found = repository.findByPk(id, true);

      await expect(found).rejects.toThrow();
      await expect(found).rejects.toThrow(ConflictException);
      await expect(found).rejects.toThrow(opts.findByPkMessage);
    });
  });

  describe('find One Method', () => {
    it('should be correct', async () => {
      const name = 'Carlos';

      await repository.create({ id: randomUUID(), name });

      const found = await repository.findOne({ name }, false);

      expect(found).toBeDefined();
      expect(found).toHaveProperty('id');
      expect(found).toHaveProperty('name');
      expect(found.name).toEqual(name);
    });

    it('should be not found', async () => {
      const name = 'Ernesto';

      await repository.create({ id: randomUUID(), name });

      const found = repository.findOne({ id: name }, true);

      await expect(found).rejects.toThrow();
      await expect(found).rejects.toThrow(NotFoundException);
      await expect(found).rejects.toThrow(opts.findOneNotFoundMessage);
    });

    it('should be throw exception', async () => {
      const id = [undefined] as unknown as string;

      const found = repository.findOne({ id, name: id }, false, {
        attributes: ['xxx'],
      });

      await expect(found).rejects.toThrow();
      await expect(found).rejects.toThrow(ConflictException);
      await expect(found).rejects.toThrow(opts.findOneMessage);
    });
  });

  describe('find All Method', () => {
    it('should be correct', async () => {
      const entities = [];
      for (let i = 0; i < length; i++) {
        entities.push({ name: `name-${i}` });
      }

      await repository.insertMany(entities);

      const list = await repository.findAll();

      expect(list).toBeDefined();
      expect(list).toHaveProperty('length');
    });

    it('should be exception', async () => {
      const list = repository.findAll({ attribute: ['xxx'] });

      await expect(list).rejects.toThrow();
      await expect(list).rejects.toThrow(ConflictException);
      await expect(list).rejects.toThrow(opts.findAllMessage);
    });
  });
});
